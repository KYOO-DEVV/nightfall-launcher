const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('nf', {
  get: () => ipcRenderer.invoke('lib:get'),
  addDialog: () => ipcRenderer.invoke('lib:add-dialog'),
  addPaths: (paths) => ipcRenderer.invoke('lib:add-paths', paths),
  pathFor: (file) => { try { return webUtils.getPathForFile(file); } catch { return null; } },
  details: (id) => ipcRenderer.invoke('details:get', id),
  colCreate: (name, gameId) => ipcRenderer.invoke('col:create', name, gameId),
  colRename: (id, name) => ipcRenderer.invoke('col:rename', id, name),
  colDelete: (id) => ipcRenderer.invoke('col:delete', id),
  colToggle: (id, gameId) => ipcRenderer.invoke('col:toggle', id, gameId),
  owned: (force) => ipcRenderer.invoke('owned:get', force),
  openStore: (uri) => ipcRenderer.invoke('owned:open', uri),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  scan: () => ipcRenderer.invoke('lib:scan'),
  connect: (indexes) => ipcRenderer.invoke('lib:connect', indexes),
  launch: (id) => ipcRenderer.invoke('game:launch', id),
  update: (id, patch) => ipcRenderer.invoke('game:update', id, patch),
  remove: (id) => ipcRenderer.invoke('game:remove', id),
  showFile: (id) => ipcRenderer.invoke('game:show-file', id),
  searchArt: (q) => ipcRenderer.invoke('art:search', q),
  applyArt: (id, appid, name) => ipcRenderer.invoke('art:apply', id, appid, name),
  refetchArt: (id) => ipcRenderer.invoke('art:refetch', id),
  customArt: (id, kind) => ipcRenderer.invoke('art:custom', id, kind),
  screenshots: (since) => ipcRenderer.invoke('stats:screenshots', since),
  settings: () => ipcRenderer.invoke('app:settings'),
  set: (key, val) => ipcRenderer.invoke('app:set', key, val),
  onChange: (cb) => ipcRenderer.on('lib:changed', (_e, data) => cb(data)),
});
